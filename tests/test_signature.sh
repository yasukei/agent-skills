#!/usr/bin/env bash
# Tests for scripts/signature.sh (both skills ship a byte-identical copy), and for pr_status.sh reading comments
# that carry its output before the original markers.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SCRIPT="$ROOT/skills/issue-to-pr/scripts/signature.sh"
PR_STATUS="$ROOT/skills/issue-to-pr/scripts/pr_status.sh"
# shellcheck source=tests/lib.sh
. "$ROOT/tests/lib.sh"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Run signature.sh with only the given environment variables (plus PATH) and the given arguments.
#   sig [VAR=value]... [-- arg...]
# Stores the results in OUT, ERR and RC
sig() {
  local envs=()
  while [ $# -gt 0 ] && [ "$1" != -- ]; do
    envs+=("$1")
    shift
  done
  [ $# -gt 0 ] && shift
  RC=0
  env -i PATH="$PATH" "${envs[@]}" "$SCRIPT" "$@" >"$WORK/out" 2>"$WORK/err" || RC=$?
  OUT="$(cat "$WORK/out")"
  ERR="$(cat "$WORK/err")"
}

# The hidden line of OUT
hidden() {
  sed -n 3p <<<"$OUT"
}

# assert_signature <display name> <agent> <model> <effort> <session> <description>
assert_signature() {
  assert_eq 0 "$RC" "$6: exit status ($ERR)"
  assert_eq "---
<sub>Generated by $1 · model \`$3\` · effort \`$4\` · session \`$5\`</sub>
<!-- agent-signature v=1 agent=$2 model=$3 effort=$4 session=$5 -->" "$OUT" "$6"
}

# Variables a Claude Code session may leave behind, e.g. when it launched Codex
CLAUDE_VARS=(CLAUDECODE=1 ANTHROPIC_MODEL=claude-opus-5-5 CLAUDE_EFFORT=high
  CLAUDE_CODE_REMOTE_SESSION_ID=cse_remote CLAUDE_CODE_SESSION_ID=local-uuid)

# ---------------------------------------------------------------------------
t "both skills ship the same script, executable"
if cmp -s "$SCRIPT" "$ROOT/skills/pr-review/scripts/signature.sh"; then pass; else fail "copies differ"; fi
if [ -x "$SCRIPT" ] && [ -x "$ROOT/skills/pr-review/scripts/signature.sh" ]; then pass; else fail "not executable"; fi

t "Claude Code cloud: the remote session ID wins over the container's session ID"
sig CLAUDECODE=1 CLAUDE_EFFORT=high CLAUDE_CODE_REMOTE_SESSION_ID=cse_01ABC CLAUDE_CODE_SESSION_ID=0f6e-uuid \
  -- --model claude-opus-5-5
assert_signature "Claude Code" claude-code claude-opus-5-5 high cse_01ABC "cloud"

t "Claude Code local: CLAUDE_CODE_SESSION_ID, model and effort from the environment"
sig CLAUDECODE=1 ANTHROPIC_MODEL=claude-sonnet-5-5 CLAUDE_EFFORT=medium CLAUDE_CODE_SESSION_ID=0f6e-uuid
assert_signature "Claude Code" claude-code claude-sonnet-5-5 medium 0f6e-uuid "local"

t "arguments win over the environment"
sig CLAUDECODE=1 ANTHROPIC_MODEL=from-env CLAUDE_EFFORT=low CLAUDE_CODE_SESSION_ID=s1 -- --model from-arg --effort max
assert_signature "Claude Code" claude-code from-arg max s1 "arguments"

t "Codex: CODEX_THREAD_ID is the session; model and effort only from arguments"
sig CODEX_THREAD_ID=019a-thread -- --model gpt-5.5-codex --effort xhigh
assert_signature Codex codex gpt-5.5-codex xhigh 019a-thread "codex with arguments"
sig CODEX_THREAD_ID=019a-thread
assert_signature Codex codex unknown unknown 019a-thread "codex without arguments"

t "an explicit --agent with no environment hints"
sig -- --agent chatgpt --model gpt-5.5
assert_signature ChatGPT chatgpt gpt-5.5 unknown unknown "chatgpt"
sig -- --agent claude-code
assert_signature "Claude Code" claude-code unknown unknown unknown "claude-code"

t "--agent codex ignores inherited Claude variables"
sig "${CLAUDE_VARS[@]}" CODEX_THREAD_ID=019a-thread -- --agent codex
assert_signature Codex codex unknown unknown 019a-thread "codex with Claude variables"
sig "${CLAUDE_VARS[@]}" -- --agent codex --effort high
assert_signature Codex codex unknown high unknown "codex without a thread ID"

t "mixed hints without --agent: unknown agent and no environment values"
sig "${CLAUDE_VARS[@]}" CODEX_THREAD_ID=019a-thread
assert_signature "an unknown agent" unknown unknown unknown unknown "mixed hints"
sig "${CLAUDE_VARS[@]}" CODEX_THREAD_ID=019a-thread -- --model m1 --effort e1
assert_signature "an unknown agent" unknown m1 e1 unknown "mixed hints with arguments"

t "no environment at all: every key present, every value unknown"
sig
assert_signature "an unknown agent" unknown unknown unknown unknown "empty environment"
assert_eq "<!-- agent-signature v=1 agent=unknown model=unknown effort=unknown session=unknown -->" "$(hidden)" "hidden line"

t "CLAUDECODE other than 1 is not a hint; ChatGPT has no environment hint"
sig CLAUDECODE=0 CLAUDE_CODE_SESSION_ID=s1
assert_signature "an unknown agent" unknown unknown unknown unknown "CLAUDECODE=0"

t "empty arguments count as not passed"
sig CLAUDECODE=1 CLAUDE_EFFORT=high CLAUDE_CODE_SESSION_ID=s1 -- --agent "" --model "" --effort ""
assert_signature "Claude Code" claude-code unknown high s1 "empty arguments"

t "rejects values that would break the signature"
for bad in "a b" 'a`b' "a<b" "a>b" "a--b"; do
  sig -- --model "$bad"
  assert_eq 2 "$RC" "exit status for '$bad'"
  assert_eq "" "$OUT" "no output for '$bad'"
done
sig -- --agent claude
assert_eq 2 "$RC" "unknown agent name"
assert_contains "$ERR" "unknown agent 'claude'" "stderr"
sig -- --model
assert_eq 2 "$RC" "missing value"
sig -- --session x
assert_eq 2 "$RC" "unknown option"

t "an environment value that would break the signature becomes unknown"
sig CLAUDECODE=1 "ANTHROPIC_MODEL=two words" CLAUDE_CODE_SESSION_ID=s1
assert_signature "Claude Code" claude-code unknown unknown s1 "model with a space"
assert_contains "$ERR" "ignoring" "stderr"

t "model IDs with brackets and dots pass through unchanged"
sig -- --agent claude-code --model "claude-opus-5-5[1m]"
assert_contains "$(hidden)" "model=claude-opus-5-5[1m] " "hidden line"

# ---------------------------------------------------------------------------
# pr_status.sh with signed comments. pr_status.sh matches the markers as substrings and never parses the signature,
# so a signature before the markers must not change what it decides. Runs on both the GraphQL path and the REST path.

export PATH="$ROOT/tests/fake-bin:$PATH"
export FAKE_GRAPHQL="$WORK/graphql.json"
export FAKE_REST_DIR="$WORK/rest"
mkdir -p "$FAKE_REST_DIR"
SHA=abc123
CHECK='{"name":"test","state":"SUCCESS","bucket":"pass","link":"l1","workflow":"CI"}'
export FAKE_CHECKS_OUT="[$CHECK]" FAKE_CHECKS_ERR="" FAKE_CHECKS_RC=0

rest_file() {
  printf '%s/%s.json' "$FAKE_REST_DIR" "$(printf '%s' "$1" | tr / _)"
}

# CI passes on the REST path too
jq -n '{ total_count: 1, check_runs: [{ name: "test", status: "completed", conclusion: "success",
  details_url: "l1", check_suite: { id: 1 } }] }' >"$(rest_file "repos/o/r/commits/$SHA/check-runs")"
echo '{ "state": "pending", "statuses": [] }' >"$(rest_file "repos/o/r/commits/$SHA/status")"
echo '{ "workflow_runs": [{ "check_suite_id": 1, "name": "CI", "event": "pull_request" }] }' \
  >"$(rest_file repos/o/r/actions/runs)"

# Build the PR (author "me", open, mergeable) for both paths.
#   write_pr <reviews> <threads> <comments>: JSON arrays of GraphQL nodes
write_pr() {
  jq -n --arg sha "$SHA" --argjson reviews "$1" --argjson threads "$2" --argjson comments "$3" '{
    data: { repository: { pullRequest: {
      url: "https://github.com/o/r/pull/1", state: "OPEN", isDraft: false, mergeable: "MERGEABLE",
      reviewDecision: null, author: { login: "me" }, headRefName: "feat/1-x", headRefOid: $sha, baseRefName: "main",
      reviews: { nodes: $reviews }, reviewThreads: { nodes: $threads }, comments: { nodes: $comments }
    } } }
  }' >"$FAKE_GRAPHQL"
  local pr user='{ login: .author.login, type: "User" }'
  pr="$(jq '.data.repository.pullRequest' "$FAKE_GRAPHQL")"
  jq --arg sha "$SHA" '{ html_url: .url, state: "open", merged: false, draft: false, mergeable: true,
    user: { login: "me", type: "User" }, head: { ref: .headRefName, sha: $sha }, base: { ref: .baseRefName } }' \
    <<<"$pr" >"$(rest_file repos/o/r/pulls/1)"
  jq "[ .reviews.nodes[] | { user: $user, state, submitted_at: .submittedAt, body } ]" <<<"$pr" \
    >"$(rest_file repos/o/r/pulls/1/reviews)"
  jq "[ .reviewThreads.nodes[].comments.nodes[] | { id: .databaseId, user: $user, body, created_at: .createdAt, html_url: .url } ]" \
    <<<"$pr" >"$(rest_file repos/o/r/pulls/1/comments)"
  jq "[ .comments.nodes[] | { id: .databaseId, user: $user, body, created_at: .createdAt, html_url: .url } ]" <<<"$pr" \
    >"$(rest_file repos/o/r/issues/1/comments)"
  jq '[ .reviewThreads.nodes[] | { resolved: .isResolved, outdated: .isOutdated, path, line,
        comment_ids: [ .comments.nodes[].databaseId ] } ]' <<<"$pr" \
    >"$(rest_file repos/o/r/pulls/1/ccr/review_threads)"
}

# review <state> <body>, comment <id> <body>: posts by "me" (author and reviewer share the account)
review() {
  jq -nc --arg s "$1" --arg b "$2" \
    '{ author: { login: "me", __typename: "User" }, state: $s, submittedAt: "2026-01-01T00:00:00Z", body: $b }'
}
comment() {
  jq -nc --argjson i "$1" --arg b "$2" \
    '{ databaseId: $i, author: { login: "me", __typename: "User" }, body: $b, createdAt: "2026-01-01T00:00:00Z", url: "u\($i)" }'
}
# thread <isResolved> <comment>...
thread() {
  local resolved="$1"
  shift
  jq -nc --argjson r "$resolved" '{ id: "T1", isResolved: $r, isOutdated: false, path: "a.sh", line: 1,
    comments: { nodes: $ARGS.positional } }' --jsonargs "$@"
}

# Run pr_status.sh on the REST path, then the GraphQL path; OUT holds the GraphQL result
run_status() {
  local rest
  RC=0
  FAKE_GRAPHQL_RC=1 FAKE_GRAPHQL_ERR="gh: GitHub GraphQL is not available (HTTP 403)" \
    "$PR_STATUS" 1 o/r >"$WORK/out" 2>"$WORK/err" || RC=$?
  assert_eq 0 "$RC" "REST path exit status ($(cat "$WORK/err"))"
  rest="$(jq -S 'del(.threads[].id)' "$WORK/out")"
  RC=0
  "$PR_STATUS" 1 o/r >"$WORK/out" 2>"$WORK/err" || RC=$?
  assert_eq 0 "$RC" "GraphQL path exit status ($(cat "$WORK/err"))"
  OUT="$(cat "$WORK/out")"
  assert_eq "$rest" "$(jq -S 'del(.threads[].id)' <<<"$OUT")" "same result on the REST path"
}

field() {
  jq -r "$1" <<<"$OUT"
}

AUTHOR_SIG="$(env -i PATH="$PATH" CLAUDECODE=1 CLAUDE_CODE_REMOTE_SESSION_ID=cse_author "$SCRIPT" --model m1 --effort high)"
REVIEWER_SIG="$(env -i PATH="$PATH" CODEX_THREAD_ID=019a-reviewer "$SCRIPT" --model m2 --effort xhigh)"
MINE='<!-- issue-to-pr -->'
BY_REVIEWER='<!-- pr-review -->'
COMPLETE='<!-- review-complete -->'

t "signed: an author reply is not reviewer activity"
write_pr "[$(review COMMENTED "")]" '[]' "[$(comment 100 "Opened the PR.

$AUTHOR_SIG
$MINE")]"
run_status
assert_eq waiting_for_review "$(field .verdict.status)" "verdict.status"
assert_eq false "$(field .review.activity)" "review.activity"
assert_eq true "$(field '.issueComments[0].byMe')" "issueComments[0].byMe"

t "signed: an author reply in a reviewer thread is the last comment by me"
write_pr "[$(review COMMENTED "## Review result

$REVIEWER_SIG
$BY_REVIEWER")]" "[$(thread false "$(comment 1 "[P2] Please fix this

$REVIEWER_SIG
$BY_REVIEWER")" "$(comment 2 "Fixed (abc1234)

$AUTHOR_SIG
$MINE")")]" '[]'
run_status
assert_eq review_in_progress "$(field .verdict.status)" "verdict.status"
assert_eq true "$(field '.threads[0].lastCommentByMe')" "lastCommentByMe"
assert_eq 1 "$(field .review.unresolvedReviewerThreadCount)" "unresolved reviewer threads"

t "signed: a no-findings review with the completion marker completes the same-account workflow"
write_pr "[$(review COMMENTED "No findings.

$REVIEWER_SIG
$COMPLETE
$BY_REVIEWER")]" '[]' '[]'
run_status
assert_eq ready "$(field .verdict.status)" "verdict.status"
assert_eq true "$(field .review.explicitCompletion)" "review.explicitCompletion"

t "signed: a review without the completion marker does not complete"
write_pr "[$(review COMMENTED "No findings.

$REVIEWER_SIG
$BY_REVIEWER")]" '[]' '[]'
run_status
assert_eq review_in_progress "$(field .verdict.status)" "verdict.status"
assert_eq false "$(field .review.explicitCompletion)" "review.explicitCompletion"

done_testing
