#!/usr/bin/env bash
# Exercise the REST-only log reader with paginated responses from the fake gh.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SCRIPT="$ROOT/skills/triage-observations/scripts/read-log.py"
# shellcheck source=tests/lib.sh
. "$ROOT/tests/lib.sh"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
export PATH="$ROOT/tests/fake-bin:$PATH"
export FAKE_REST_DIR="$WORK"
export FAKE_GH_LOG="$WORK/calls"
ISSUE="$WORK/repos_o_r_issues_50.json"
COMMENTS="$WORK/repos_o_r_issues_50_comments.json"
LOG_URL=https://github.com/o/r/issues/50
FIRST="$LOG_URL#issuecomment-101"
SECOND="$LOG_URL#issuecomment-102"
MARKER='<!-- collect-observations:log -->'

write_issue() {
  jq -Rs --arg url "$LOG_URL" '{number: 50, html_url: $url, body: .}' >"$ISSUE"
}

comment() {
  jq -Rsc --arg url "$1" '{html_url: $url, body: .}'
}

read_log() {
  : >"$FAKE_GH_LOG"
  RC=0
  "$SCRIPT" "$@" >"$WORK/out" 2>"$WORK/err" || RC=$?
  OUT="$(cat "$WORK/out")"
  ERR="$(cat "$WORK/err")"
}

field() {
  jq -c "$1" <<<"$OUT"
}

table() {
  cat <<'MD'
## Scope

**Status**

| Item | Summary | Status |
|---|---|---|
MD
}

t "open and decided rows link to the correct items across paginated comments"
{
  table
  cat <<MD
| [#40-1]($FIRST) | Empty input | open |
| [#40-2]($FIRST) | Earlier fix | issue #70 |
| [#41-1]($SECOND) | Error A \| B | open |
| [#41-2]($SECOND) | Shared work | in #72 |
| [#41-3]($SECOND) | Obsolete | dropped (was A \| B) |
| [#41-4]($SECOND) | Parked | moved to [next log](https://github.com/o/r/issues/51) |

$MARKER
MD
} | write_issue
first="$(comment "$FIRST" <<'MD'
### PR #40 (issue #39) — at 123abcd

**#40-1** — `src/a.py:12`, `tests/a.py`
- Observation: Empty input can reach this path.
  Check both entry points.
- Not raised because: Outside the issue.
- Related: #60
- Source: reviewer

### PR #40 (issue #39) — at 456abcd

**#40-2** — `src/b.py`
- Observation: The fallback is unused.
- Not raised because: No current effect.
- Related: none
- Source: implementer

Copied from https://github.com/o/r/pull/40#issuecomment-201

---
<sub>Generated by ...</sub>
<!-- collect-observations:source pr=40 comment=201 -->
MD
)"
second="$(comment "$SECOND" <<'MD'
### PR #41 (issue #38) — at 789abcd

**#41-1** — `src/c.py:5`
- 観察：A と B の場合に失敗する。
- 見送った理由：範囲外。
- 関連：なし
- 出典：実装者

**#41-2** — `src/c.py:6`
- Observation: Same work as the open issue.
- Not raised because: Outside the issue.
- Related: #72
- Source: reviewer

**#41-3** — `src/c.py:7`
- Observation: Both error paths use this function.
- Not raised because: Already fixed elsewhere.
- Related: none
- Source: reviewer

**#41-4** — `src/c.py:8`
- Observation: A cleanup would help here.
- Not raised because: Outside the issue.
- Related: next milestone
- Source: implementer

Copied from https://github.com/o/r/pull/41#issuecomment-202

---
<sub>Generated by ...</sub>
<!-- collect-observations:source pr=41 comment=202 -->
MD
)"
printf '[%s]\n[%s]\n' "$first" "$second" >"$COMMENTS"

read_log o/r '#50'
assert_eq 0 "$RC" "exit status ($ERR)"
assert_eq '["o/r",50,"https://github.com/o/r/issues/50"]' "$(field '[.repository,.number,.url]')" "log identity"
assert_eq '["#40-1","#40-2","#41-1","#41-2","#41-3","#41-4"]' "$(field '[.rows[].id]')" "rows in table order"
assert_eq '["open","issue #70","open","in #72","dropped (was A \\| B)","moved to [next log](https://github.com/o/r/issues/51)"]' \
  "$(field '[.rows[].status]')" "open and existing status values"
assert_eq '"Error A \\| B"' "$(field '.rows[2].summary')" "escaped pipe stays in summary"
expected="$(jq -cn '{pr: 40, issue: 39, sha: "123abcd", location: "`src/a.py:12`, `tests/a.py`",
  observation: "Empty input can reach this path.\n  Check both entry points.",
  not_raised_because: "Outside the issue.", related: "#60", source: "reviewer"}')"
assert_eq "$expected" "$(field '.rows[0].item')" "all fields including the multiline observation"
assert_eq '"456abcd"' "$(field '.rows[1].item.sha')" "next SHA group in the same comment"
assert_eq "\"$SECOND\"" "$(field '.rows[2].comment_url')" "link to the second page comment"
assert_eq '["A と B の場合に失敗する。","範囲外。","なし","実装者"]' \
  "$(field '.rows[2].item | [.observation,.not_raised_because,.related,.source]')" "translated labels"
assert_eq '[true,true,true,true,true,true]' "$(field '[.rows[] | .item != null]')" "fields for decided rows too"
assert_contains "$(cat "$FAKE_GH_LOG")" 'api --paginate repos/o/r/issues/50/comments?per_page=100' "requests every page"

t "rows-only mode reads the whole status table in a single request"
read_log o/r 50 --rows-only
assert_eq 0 "$RC" "exit status ($ERR)"
assert_eq '["#40-1","#40-2","#41-1","#41-2","#41-3","#41-4"]' "$(field '[.rows[].id]')" "all rows"
assert_eq '["#40-1","#41-1"]' "$(field '[.rows[] | select(.status == "open") | .id]')" "open rows"
assert_eq '"moved to [next log](https://github.com/o/r/issues/51)"' "$(field '.rows[-1].status')" "moved status"
assert_eq 'api repos/o/r/issues/50 --hostname github.com' "$(cat "$FAKE_GH_LOG")" "only reads the issue"

t "an item found only in another comment is still missing from its linked comment"
{
  table
  printf '| [#40-1](%s) | Wrong comment | open |\n\n%s\n' "$SECOND" "$MARKER"
} | write_issue
read_log o/r 50
assert_eq 0 "$RC" "exit status ($ERR)"
assert_eq 'null' "$(field '.rows[0].item')" "no item recovered from a different comment"
assert_contains "$OUT" 'item_error' "missing item is explained"

t "an error fetching comments fails the read without partial JSON"
printf 'gh: Service unavailable (HTTP 503)\n' >"$COMMENTS.err"
read_log o/r 50
assert_eq 2 "$RC" "exit status"
assert_eq "" "$OUT" "no partial JSON"
assert_contains "$ERR" 'repos/o/r/issues/50/comments' "failed resource"
assert_contains "$ERR" 'HTTP 503' "API error"
rm "$COMMENTS.err"

t "a marked issue with no rows needs no comments"
{ table; printf '\n%s\n' "$MARKER"; } | write_issue
read_log o/r 50
assert_eq 0 "$RC" "exit status ($ERR)"
assert_eq '[]' "$(field '.rows')" "empty table"
assert_eq 'api repos/o/r/issues/50 --hostname github.com' "$(cat "$FAKE_GH_LOG")" "only reads the issue"

t "the resolved host is sent with issue and comments calls"
{
  table
  printf '| [#40-1](%s) | Empty input | open |\n\n%s\n' "$FIRST" "$MARKER"
} | write_issue
read_log o/r 50 --hostname git.example.com
assert_eq 0 "$RC" "exit status ($ERR)"
assert_contains "$(cat "$FAKE_GH_LOG")" 'api repos/o/r/issues/50 --hostname git.example.com' "issue host"
assert_contains "$(cat "$FAKE_GH_LOG")" 'api --paginate repos/o/r/issues/50/comments?per_page=100 --hostname git.example.com' "comments host"

t "a pull request or an unmarked issue cannot be used as the log"
jq '.pull_request = {}' "$ISSUE" >"$WORK/pr"
mv "$WORK/pr" "$ISSUE"
read_log o/r 50
assert_eq 2 "$RC" "exit status"
assert_contains "$ERR" 'is a pull request' "PR rejected"
table | write_issue
read_log o/r 50
assert_eq 2 "$RC" "exit status"
assert_contains "$ERR" 'missing the log marker' "unmarked issue rejected"

t "invalid input or an invalid status row fails before fetching comments"
read_log o/r '##50'
assert_eq 2 "$RC" "invalid issue number"
assert_eq '' "$(cat "$FAKE_GH_LOG")" "no API call for invalid input"
{ table; printf '| invalid | Unlinked row | open |\n\n%s\n' "$MARKER"; } | write_issue
read_log o/r 50
assert_eq 2 "$RC" "exit status"
assert_contains "$ERR" 'invalid status row' "malformed row is reported"
assert_eq '' "$OUT" "no partial rows"

done_testing
